/**
 * Build-time support for installing the apps (roadmap items 38 and 34).
 *
 * The plugin writes, next to the built app:
 * - `manifest.webmanifest`: name, icon, standalone display, and
 *   `file_handlers` so an installed app opens its work files from the OS;
 * - `icon.svg`;
 * - `sw.js`: a service worker that caches every built file for offline use.
 *   Its version is a hash of the build's file names, so each new build is a
 *   new worker; it waits until the app tells it to take over (see
 *   `registerAppUpdates` in `@gs2d/ui`), so an open tab never switches
 *   versions mid-edit.
 *
 * Nothing changes in development: the plugin only runs for `vp build`.
 */

export interface PwaOptions {
  name: string;
  shortName: string;
  description: string;
  themeColor: string;
  backgroundColor: string;
  /** SVG markup of the app icon. */
  iconSvg: string;
  /** Work files the installed app opens from the OS: MIME type → extensions. */
  fileTypes?: Record<string, string[]>;
}

/** Small, stable string hash (FNV-1a) for the cache version. */
function hash(text: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(36);
}

/** The service worker, with the cache version and the files to precache filled in. */
export function serviceWorkerSource(version: string, files: string[]): string {
  return `/* Generated by @gs2d/workspace/vite/pwa.ts. */
const VERSION = ${JSON.stringify(version)};
// Per app (scope), so two apps served from one origin never delete each other's caches.
const PREFIX = "gs2d:" + self.registration.scope + ":";
const CACHE = PREFIX + VERSION;
// Caches from before Game Studio 2D.
const LEGACY_PREFIX = "foundry2d:" + self.registration.scope + ":";
const FILES = ${JSON.stringify(["./", ...files])};
const OFFLINE_PAGE =
  '<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width">' +
  '<title>Offline</title><body style="font:15px system-ui;background:#0e0e11;color:#f4f4f5;padding:40px">' +
  "<h1>You're offline</h1><p>This page isn't saved for offline use yet. Open it once while online.</p>" +
  '<p><a style="color:#38bdf8" href="' + self.registration.scope + '">Back to the start page</a></p>';

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((k) => (k.startsWith(PREFIX) && k !== CACHE) || k.startsWith(LEGACY_PREFIX))
            .map((k) => caches.delete(k))
        )
      )
      .then(() => self.clients.claim())
  );
});

// The app asks a waiting worker to take over when the user chooses to reload.
self.addEventListener("message", (event) => {
  if (event.data === "skip-waiting") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === "navigate") {
    // Pages: the network when online (so a new build is noticed), the cached shell offline.
    // Only for this app's own page: the studio's worker covers the whole site, and its page
    // under another app's address would load nothing (that app's worker answers for it, or
    // nobody does).
    const own = new URL(request.url).pathname === new URL(self.registration.scope).pathname;
    event.respondWith(
      fetch(request).catch(() =>
        own
          ? caches.match("./", { ignoreSearch: true, ignoreVary: true })
          : new Response(OFFLINE_PAGE, { headers: { "Content-Type": "text/html; charset=utf-8" } })
      )
    );
    return;
  }
  // Built files have hashed names and never change: the cache first.
  event.respondWith(
    // Ignoring Vary: servers send "Vary: Origin", and module scripts are requested with an
    // Origin header the precache requests didn't have, so every lookup would miss offline.
    caches.match(request, { ignoreVary: true }).then(
      (cached) =>
        cached ||
        fetch(request).then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
    )
  );
});
`;
}

interface OutputBundle {
  [fileName: string]: unknown;
}

interface EmitContext {
  emitFile(file: { type: "asset"; fileName: string; source: string }): void;
}

/**
 * Only the offline copy (a service worker, no manifest): for pages that
 * aren't apps to install but should work offline inside the installed
 * studio, like the manual.
 */
export function offlineWorker() {
  return {
    name: "gs2d-offline-worker",
    apply: "build" as const,
    generateBundle(this: EmitContext, _output: unknown, bundle: OutputBundle): void {
      const files = Object.keys(bundle)
        .filter((f) => !f.endsWith(".map"))
        .sort()
        .map((f) => `./${f}`);
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: serviceWorkerSource(hash(files.join("\n")), files),
      });
    },
  };
}

/** The Vite plugin; add it to `plugins` in an app's `vite.config.ts`. */
export function foundryPwa(options: PwaOptions) {
  return {
    name: "gs2d-pwa",
    apply: "build" as const,
    transformIndexHtml(html: string): string {
      const tags = [
        `<link rel="manifest" href="./manifest.webmanifest" />`,
        `<link rel="icon" href="./icon.svg" type="image/svg+xml" />`,
        `<meta name="theme-color" content="${options.themeColor}" />`,
      ].join("\n    ");
      return html.replace("</head>", `    ${tags}\n  </head>`);
    },
    generateBundle(this: EmitContext, _output: unknown, bundle: OutputBundle): void {
      const manifest = {
        name: options.name,
        short_name: options.shortName,
        description: options.description,
        start_url: "./",
        scope: "./",
        display: "standalone",
        theme_color: options.themeColor,
        background_color: options.backgroundColor,
        icons: [{ src: "./icon.svg", sizes: "any", type: "image/svg+xml", purpose: "any" }],
        ...(options.fileTypes
          ? {
              file_handlers: [{ action: "./", accept: options.fileTypes }],
              launch_handler: { client_mode: "focus-existing" },
            }
          : {}),
      };
      this.emitFile({ type: "asset", fileName: "icon.svg", source: options.iconSvg });
      this.emitFile({
        type: "asset",
        fileName: "manifest.webmanifest",
        source: JSON.stringify(manifest, null, 2),
      });
      const files = [
        ...Object.keys(bundle).filter((f) => !f.endsWith(".map")),
        "icon.svg",
        "manifest.webmanifest",
      ]
        .sort()
        .map((f) => `./${f}`);
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: serviceWorkerSource(hash(files.join("\n")), files),
      });
    },
  };
}
